import argparse
import re
from datetime import datetime
from pathlib import Path
from kokoro import KPipeline
from pydub import AudioSegment
import soundfile as sf
import io

# 1. Helper function to turn SRT time (00:00:02,500) into milliseconds
def srt_time_to_ms(time_str):
    t = datetime.strptime(time_str.strip(), "%H:%M:%S,%f")
    return (t.hour * 3600 + t.minute * 60 + t.second) * 1000 + t.microsecond // 1000

# 2. Parse the SRT file into a clean list of cues
def parse_srt(srt_path):
    with open(srt_path, 'r', encoding='utf-8') as f:
        content = f.read()
    
    # Split by double newlines to separate subtitle blocks
    blocks = content.strip().split('\n\n')
    cues = []
    
    for block in blocks:
        lines = block.split('\n')
        if len(lines) >= 3:
            # Extract timestamps
            time_match = re.match(r'(\d+:\d+:\d+,\d+)\s+-->\s+(\d+:\d+:\d+,\d+)', lines[1])
            if time_match:
                start_ms = srt_time_to_ms(time_match.group(1))
                end_ms = srt_time_to_ms(time_match.group(2))
                text = " ".join(lines[2:])
                cues.append({'start': start_ms, 'end': end_ms, 'text': text})
    return cues

def blend_voices(pipeline, voice_config):
    """
    Parses a string like 'bm_george:0.6,bm_lewis:0.4' 
    and returns a single blended voice tensor.
    """
    blended_tensor = None
    
    # Split the string by commas to get individual components
    parts = voice_config.split(',')
    
    for part in parts:
        # Separate the voice name from its weight (e.g., 'bm_george' and '0.6')
        name, weight_str = part.split(':')
        weight = float(weight_str)
        
        # Load the raw voice vector using the pipeline's internal load mechanism
        # This correctly downloads 'bm_george.pt' or 'bm_lewis.pt' from Hugging Face
        voice_tensor = pipeline.load_voice(name)
        
        # Add the weighted tensor to our blend
        if blended_tensor is None:
            blended_tensor = voice_tensor * weight
        else:
            blended_tensor += voice_tensor * weight
            
    return blended_tensor


# 3. Main processing function
def srt_to_audio(srt_path, output_path, voice='bm_george:0.9,bm_lewis:0.1', output_format='wav'):
    cues = parse_srt(srt_path)
    
    # Initialize Kokoro (using 'a' for American English, 'b' for British English)
    pipeline = KPipeline(lang_code='b') 
    
    # Create a blank audio canvas
    final_audio = AudioSegment.empty()
    current_time_ms = 0

     # Check if we are passing a blend or a single voice
    if ',' in voice or ':' in voice:
        # Generate the mathematically combined custom voice tensor
        active_voice = blend_voices(pipeline, voice)
    else:
        # Fallback to standard single voice string if no colon/comma is used
        active_voice = voice


    print(f"Processing {len(cues)} subtitle lines...")

    for i, cue in enumerate(cues):
        # Calculate how much silence we need before this subtitle starts
        silence_needed = cue['start'] - current_time_ms
        if silence_needed > 0:
            final_audio += AudioSegment.silent(duration=silence_needed)
            current_time_ms += silence_needed
        
        # Generate the speech using Kokoro
        generator = pipeline(cue['text'], voice=active_voice, speed=1.0, split_pattern=r'\n')
        
        # Combine the audio chunks generated by Kokoro
        for _, _, audio in generator:
            # Convert raw numpy audio from Kokoro into a Pydub AudioSegment
            byte_io = io.BytesIO()
            sf.write(byte_io, audio, 24000, format='WAV') # Kokoro outputs at 24kHz
            byte_io.seek(0)
            speech_segment = AudioSegment.from_wav(byte_io)
            
            # Add speech to our timeline
            final_audio += speech_segment
            current_time_ms += len(speech_segment)
            
    # Export the final synchronized audio track
    final_audio.export(output_path, format=output_format)
    print(f"Success! Audio saved to {output_path}")

def main():
    parser = argparse.ArgumentParser(description="Convert an SRT subtitle file to a synchronized audio voiceover.")
    parser.add_argument("srt_path", type=Path, help="Path to the input SRT file")
    parser.add_argument("-format", "--format", choices=("wav", "mp3"), default="wav",
                        help="Output audio format (default: wav)")
    args = parser.parse_args()

    output_path = Path.cwd() / args.srt_path.with_suffix(f".{args.format}").name
    srt_to_audio(args.srt_path, str(output_path), output_format=args.format)


if __name__ == "__main__":
    main()
